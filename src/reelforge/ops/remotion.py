"""S3/S7/S8 ops: generate brand.ts from brand.json, write render props, render stills and videos with Remotion."""

from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path
from typing import Iterable, Optional

from ..project import Project
from ..schemas import Brand
from .env import REMOTION_PORT, free_port, node_dir, port_free

GL = os.environ.get("REELFORGE_GL", "angle")


def _font_module(family: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", family)


def write_brand_ts(brand: Brand) -> Path:
    """brand.ts is generated from brand.json: colour tokens, fonts via @remotion/google-fonts, motion."""
    fams: dict[str, set[str]] = {}
    roles = {}
    for role, spec in brand.fonts.items():
        fam, _, wt = spec.partition(":")
        fams.setdefault(fam, set()).add(wt or "400")
        roles[role] = (fam, wt or "400")
    imports, loads, names = [], [], {}
    for i, (fam, weights) in enumerate(sorted(fams.items())):
        mod = _font_module(fam)
        imports.append(f'import {{ loadFont as load{i} }} from "@remotion/google-fonts/{mod}";')
        loads.append(f'const f{i} = load{i}("normal", {{ weights: {json.dumps(sorted(weights))}, subsets: ["latin"] }});')
        names[fam] = f"f{i}.fontFamily"
    fonts = {
        "display": names[roles["display"][0]], "displayWeight": roles["display"][1],
        "body": names[roles.get("body", roles["display"])[0]], "bodyWeight": roles.get("body", roles["display"])[1],
        "mono": names[roles.get("mono", roles["display"])[0]], "monoWeight": roles.get("mono", roles["display"])[1],
    }
    fonts_ts = ",\n    ".join(f"{k}: {v}" if not k.endswith("Weight") else f"{k}: {int(v)}" for k, v in fonts.items())
    src = f"""// GENERATED by reelforge from brand.json - do not edit by hand (run `reelforge brand`).
{chr(10).join(imports)}

{chr(10).join(loads)}

export const BRAND = {{
  colors: {json.dumps(brand.colors)},
  fonts: {{
    {fonts_ts},
  }},
  tracking: {json.dumps(brand.tracking)},
  motion: {{ defaultEase: {json.dumps(brand.motion.get("default_ease", "outExpo"))}, uiSpring: {json.dumps(brand.motion.get("ui_spring", {"damping": 13}))} }},
  motif: {json.dumps(brand.motif)},
}} as const;

export const C = BRAND.colors;
export const F = BRAND.fonts;
"""
    out = node_dir("remotion") / "src" / "generated" / "brand.ts"
    out.write_text(src)
    return out


def sfx_files(p: Project) -> dict[str, str]:
    d = p.path("audio/sfx")
    return {f.stem: f"audio/sfx/{f.name}" for f in sorted(d.glob("*.mp3"))} if d.exists() else {}


def write_props(p: Project, asset_base: str, debug: bool = False) -> Path:
    props = {
        "timeline": p.read_json("plan/timeline.json"),
        "takes": p.read_json("plan/takes.json", {}),
        "assetBase": asset_base,
        "sfxFiles": sfx_files(p),
        "debug": debug,
    }
    f = p.path("render", "props.json")
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(json.dumps(props))
    return f


def _render_port() -> int:
    # Never assume 3000 is free; pin 3700 if available, else a random free port.
    return REMOTION_PORT if port_free(REMOTION_PORT) else free_port()


def render_video(p: Project, comp: str, props: Path, out: Path, concurrency: int = 4, timeout_ms: int = 240000,
                 crf: int = 17, frames: Optional[str] = None, scale: float = 1.0, log=None) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["npx", "remotion", "render", "src/index.ts", comp, str(out), f"--props={props}",
           "--codec=h264", f"--crf={crf}", "--pixel-format=yuv420p", "--color-space=bt709", "--audio-bitrate=320k",
           f"--concurrency={concurrency}", f"--timeout={timeout_ms}", f"--port={_render_port()}", f"--gl={GL}",
           "--log=warn"]
    if frames:
        cmd.append(f"--frames={frames}")
    if scale != 1.0:
        cmd.append(f"--scale={scale}")
    r = subprocess.run(cmd, cwd=node_dir("remotion"), capture_output=True, text=True)
    logf = out.with_suffix(".render.log")
    logf.write_text(r.stdout + "\n" + r.stderr)
    if r.returncode != 0:
        raise RuntimeError(f"remotion render {comp} failed (see {logf}):\n{r.stderr[-1500:]}")
    return out


def render_stills(p: Project, props: Path, jobs: list[dict], out_dir: Path, scale: float = 0.5,
                  fmt: str = "jpeg") -> list[Path]:
    """jobs: [{comp, frames: [...]}]. One bundle, one browser, many stills."""
    job = {"props": str(props), "out": str(out_dir), "scale": scale, "format": fmt, "gl": GL,
           "port": free_port(), "jobs": jobs}
    jf = out_dir / "stills.job.json"
    out_dir.mkdir(parents=True, exist_ok=True)
    jf.write_text(json.dumps(job))
    r = subprocess.run(["node", "scripts/stills.mjs", str(jf)], cwd=node_dir("remotion"), capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"render stills failed:\n{r.stderr[-2000:]}")
    return [Path(x) for x in json.loads((out_dir / "stills.json").read_text())]


def compositions(p: Project, cuts: Optional[Iterable[str]] = None, formats: Optional[Iterable[str]] = None) -> list[tuple[str, str, str]]:
    tl = p.timeline
    out = []
    for ct in tl.cuts:
        if cuts and ct.name not in cuts:
            continue
        for f in ct.formats:
            if formats and f not in formats:
                continue
            out.append((f"{ct.name}-{f}", ct.name, f))
    return out


def npm_install(name: str) -> str:
    d = node_dir(name)
    r = subprocess.run(["npm", "install", "--no-audit", "--no-fund"], cwd=d, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr[-2000:])
    return r.stdout[-500:]
